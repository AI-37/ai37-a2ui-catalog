/** Строки — любые, формы по числу — `PluralMessage`; ключи те же, что у русского словаря. */
type Widen<T> = T extends string
  ? string
  : T extends {other: string}
    ? PluralMessage
    : {readonly [K in keyof T]: Widen<T[K]>};

/** Словарь подписей каталога: форма задаётся русским словарём. */
