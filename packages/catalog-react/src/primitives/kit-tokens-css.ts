import {declareTokens} from './declare-tokens';

/**
 * Слой токенов на корне набора: всё остальное читает только эти имена.
 *
 * Выше — выбор темы. Тему выбирает поверхность, а не набор: `color-scheme`
 * наследуется, поэтому объявление хоста доходит до `.a2ui-kit` сквозь его
 * собственный слой токенов (`kit-tokens.ts`). Атрибут — знакомая обёртка над
 * тем же свойством; работает и на предке, и на самом корне набора: это частный
 * случай наследования, отдельной ветки он не требует.
 *
 * `:where()` — нулевая специфичность: хост, написавший `color-scheme` сам,
 * должен остаться сильнее. Само `.a2ui-kit` `color-scheme` НЕ объявляет —
 * иначе повторило бы ту же ошибку, из-за которой набор и не темнел.
 *
 * По умолчанию (хост молчит) `color-scheme` = `normal`, и `light-dark()` берёт
 * первое значение — набор светлый даже при тёмной ОС. Это выбор: компонент
 * живёт внутри чужой ленты, и самовольно потемневшая карточка в светлом чате —
 * тот же дефект, только зеркальный. «Следовать системе» хост пишет сам:
 * `color-scheme: light dark`.
 */
export const KIT_TOKENS_CSS = `
:where([data-a2ui-theme='light']) { color-scheme: light; }
:where([data-a2ui-theme='dark']) { color-scheme: dark; }

.a2ui-kit {
${declareTokens()}

  /* Корень набора — он же контейнер раскладки: ширину меряем один раз и по
     нему, а не по каждой форме в отдельности. Форма живёт внутри отступов
     карточки и её тела, это на ~60px уже корня, и пороги, замеренные по ней,
     разъезжались бы с порогами остальных сеток набора. */
  container-type: inline-size;
  container-name: a2ui-kit;
  /* width обязателен: inline-size включает size containment, и во флекс-хосте
     корень схлопнулся бы в ноль. */
  width: 100%;
  min-width: 0;

  font-family: var(--a2ui-font);
  color: var(--a2ui-text-color);
}
`;
