/**
 * Радиус полуокружности № 50 веера, м. Правило листа: полуокружность № 30
 * ложится на плоскость остекления, то есть на расстояние от расчётной точки
 * до середины толщины оконной стены. Отсюда одна цена деления на разрезе и на
 * плане — оба листа считают её от тех же lт и Δст (Решение 4 design.md).
 */
export function graphRadius50(lt: number, wallThickness: number): number {
  return ((lt + wallThickness / 2) / 30) * 50;
}
