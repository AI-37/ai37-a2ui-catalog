/**
 * Ключ правленного поля: `{локальный id экрана}::{поле}`. Ключ по id, а не по
 * индексу: удаление помещения (расчётной точки, здания) из середины сдвинуло бы
 * индексы, и метка «изменено вами» переехала бы на соседа.
 */
export function calcTouchedKey(screenId: string, field: string): string {
  return `${screenId}::${field}`;
}
