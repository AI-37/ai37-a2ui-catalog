/**
 * Подпись рядом с кнопкой submit'а: сколько конструкций проходит норму.
 *
 * Мотив — дефект прода: подвал печатал «проходит 0 из 0» при трёх заполненных
 * конструкциях, у которых live-Rпр уже был посчитан и виден в чипах. Формально
 * честно (сравнивать не с чем: агент не прислал `rnorm`), но читается как
 * «ничего не проходит» — то есть как приговор расчёту, а не как «нормы ещё нет».
 *
 * Формулировка агностична к эмитенту: почему нормы нет — знает агент (у
 * теплотехники это неполный Шаг 1), и он же говорит это своим текстом.
 * Компонент каталога общий и причину не выдумывает.
 *
 * Смешанный набор не умалчивает об остатке: «проходит 2 из 3» при пяти
 * конструкциях скрывало бы две.
 */
export function passingSummary(passing: number, comparable: number, total: number): string {
  if (total === 0) {
    return 'конструкций пока нет';
  }

  if (comparable === 0) {
    return 'норма не задана — сравнивать не с чем';
  }

  const head = `проходит ${passing} из ${comparable}`;
  const withoutNorm = total - comparable;

  return withoutNorm > 0 ? `${head} · для ${withoutNorm} нормы нет` : head;
}
