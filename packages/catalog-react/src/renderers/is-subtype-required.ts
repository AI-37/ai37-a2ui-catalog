import type {ConstructionTypeConfig} from '@ai37/a2ui-catalog-schemas';

/**
 * Обязательна ли разновидность у типа конструкции. Правило не зашито в клиент:
 * его говорит агент формой `alphaN` — записью по разновидностям αн задан ровно
 * тому типу, где без разновидности его не выбрать (таблица 6 СП 50: чердак 12,
 * подполье вентилируемое 17, невентилируемое 6, пол по грунту — без члена
 * 1/αн). Одно число — разновидности у типа нет.
 *
 * Та же механика, что у паспортного Rпр: клиент не знает, что окна считаются
 * по паспорту, — ему это сказал агент полем `hasLayers`.
 */
export function isSubtypeRequired(config: ConstructionTypeConfig | undefined): boolean {
  return typeof config?.alphaN === 'object';
}
